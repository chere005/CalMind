import { expect, test } from '@playwright/test';

test('note type comes first and daily cards stay together, save, and survive type changes', async ({ page }) => {
  const user = `log${Date.now()}`;
  await page.goto('.');
  await page.getByText('Sign up', { exact: true }).click();
  await page.getByPlaceholder('Username').fill(user);
  await page.getByPlaceholder('Email').fill(`${user}@example.com`);
  await page.getByPlaceholder('Password', { exact: true }).fill('e2epassword');
  await page.getByPlaceholder('Confirm password').fill('e2epassword');
  await page.getByText('Sign up', { exact: true }).click();
  await page.getByTestId('tab-notes').click();
  await page.getByTestId('secadd-General').first().click();
  await page.getByTestId('note-title').fill('My daily journal');
  await page.getByTestId('note-body-view').click();
  await page.getByTestId('note-body-edit').fill('Keep this introduction');
  const picker = page.getByTestId('note-type');
  expect(await picker.evaluate((node) => node.parentElement?.firstElementChild === node)).toBe(true);
  await picker.click();
  await page.getByText('Daily log', { exact: true }).click();
  await expect(page.getByTestId('daily-log-card')).toHaveCount(1);
  await page.getByTestId('daily-food').fill('Soup');
  await page.getByTestId('daily-exercise').fill('Walk');
  await page.getByTestId('daily-mood').fill('Calm');
  await page.getByTestId('daily-log-add').click();
  await expect(page.getByTestId('daily-log-card')).toHaveCount(2);
  await expect(page.getByTestId('daily-food').nth(1)).toHaveValue('Soup');
  await page.getByTestId('daily-food').first().fill('Breakfast');
  await picker.click();
  await page.getByText('Note', { exact: true }).click();
  await expect(page.getByTestId('note-body-view')).toHaveText('Keep this introduction');
  await picker.click();
  await page.getByText('Daily log', { exact: true }).click();
  await expect(page.getByTestId('daily-log-card')).toHaveCount(2);
  await page.getByTestId('note-back').click();
  await expect(page.getByTestId('note-row')).toHaveCount(1);
  await page.reload();
  await page.getByTestId('tab-notes').click();
  await page.getByTestId('note-row').filter({ hasText: 'My daily journal' }).click();
  await expect(page.getByTestId('daily-log-card')).toHaveCount(2);
  await expect(page.getByTestId('daily-food').first()).toHaveValue('Breakfast');
  await expect(page.getByTestId('daily-mood').nth(1)).toHaveValue('Calm');
});
